//! Adaptador e instalador de la extensión PI.
use crate::claude::{confirm, Scope};
use anyhow::{bail, Context, Result};
use galgo_proto::HookEvent;
use serde_json::Value;
use std::{io::{Read, Write}, os::unix::fs::{OpenOptionsExt, PermissionsExt}, path::{Path, PathBuf}};

const MARKER: &str = "// galgo-managed-pi-extension v1; generated by galgo hooks install pi\n";
const TEMPLATE: &str = include_str!("pi-extension.ts");

pub fn map_event(value: &Value) -> Option<(HookEvent, Option<String>)> {
    let text = |key: &str| value.get(key).and_then(Value::as_str)
        .map(str::trim).filter(|s| !s.is_empty()).map(|s| {
            if s.chars().count() > 600 { format!("{}…", s.chars().take(600).collect::<String>()) } else { s.to_owned() }
        });
    match value.get("type")?.as_str()? {
        "before_agent_start" if value.get("messageType")?.as_str()? == "user" => Some((HookEvent::PromptSubmitted, None)),
        "agent_start" | "ui_prompt_end" => Some((HookEvent::Working, None)),
        "session_start" => match value.get("idle")?.as_bool()? {
            true => Some((HookEvent::Idle, None)),
            false => Some((HookEvent::Working, None)),
        },
        "ui_prompt_start" => Some((HookEvent::Blocked, text("title"))),
        "agent_settled" => match value.get("outcome")?.as_str()? {
            "completed" => Some((HookEvent::TurnEnded, text("summary"))),
            "failed" => Some((HookEvent::Failed, text("error").or_else(|| text("summary")))),
            "unknown" => Some((HookEvent::Idle, None)),
            _ => None,
        },
        _ => None,
    }
}

fn path(home: &Path) -> PathBuf { home.join(".pi/agent/extensions/galgo.ts") }
fn backup(path: &Path) -> PathBuf { path.with_file_name("galgo.ts.galgo-bak") }
fn home_path(scope: Scope) -> Result<PathBuf> {
    if !matches!(scope, Scope::User) { bail!("PI solo admite --scope user"); }
    Ok(path(Path::new(&std::env::var_os("HOME").context("HOME no está definido")?)))
}
fn contents(exe: &Path) -> Result<String> {
    let exe = exe.to_str().context("ruta del ejecutable no es UTF-8")?;
    Ok(TEMPLATE.replace("__GALGO_EXECUTABLE__", &serde_json::to_string(exe)?))
}
fn current(path: &Path) -> Result<Option<String>> {
    match std::fs::symlink_metadata(path) {
        Ok(meta) if meta.file_type().is_symlink() => bail!("no se modifica el symlink {}", path.display()),
        Ok(_) => Ok(Some(std::fs::read_to_string(path)?)),
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => Ok(None),
        Err(e) => Err(e.into()),
    }
}
fn write_atomic(path: &Path, text: &str) -> Result<()> {
    let mut random = [0u8; 8];
    std::fs::File::open("/dev/urandom")?.read_exact(&mut random)?;
    let tmp = path.with_file_name(format!(".galgo.ts.{}.{:016x}.tmp", std::process::id(), u64::from_ne_bytes(random)));
    let mut file = std::fs::OpenOptions::new().write(true).create_new(true).mode(0o600).open(&tmp)?;
    let result = (|| -> Result<()> { file.write_all(text.as_bytes())?; std::fs::rename(&tmp, path)?; Ok(()) })();
    if result.is_err() { let _ = std::fs::remove_file(&tmp); }
    result
}
fn install(path: &Path, exe: &Path) -> Result<bool> {
    let text = contents(exe)?;
    let existing = current(path)?;
    if existing.as_deref() == Some(text.as_str()) { return Ok(false); }
    std::fs::create_dir_all(path.parent().context("ruta sin directorio")?)?;
    let mut created_backup = false;
    if let Some(old) = &existing {
        if !old.starts_with(MARKER) {
            let backup = backup(path);
            // create_new evita sobrescribir un respaldo anterior, incluso un symlink.
            let mode = std::fs::metadata(path)?.permissions().mode() & 0o7777;
            let mut file = std::fs::OpenOptions::new().write(true).create_new(true).mode(mode).open(&backup)
                .with_context(|| format!("no pude crear respaldo {}; no se modificó la extensión", backup.display()))?;
            if let Err(e) = file.set_permissions(std::fs::Permissions::from_mode(mode)).and_then(|_| file.write_all(old.as_bytes())) { let _ = std::fs::remove_file(&backup); return Err(e.into()); }
            created_backup = true;
        }
    }
    if let Err(e) = write_atomic(path, &text) {
        if created_backup { let _ = std::fs::remove_file(backup(path)); }
        return Err(e);
    }
    Ok(true)
}
fn uninstall(path: &Path) -> Result<bool> {
    let Some(existing) = current(path)? else { return Ok(false) };
    if !existing.starts_with(MARKER) { return Ok(false); }
    let backup = backup(path);
    match std::fs::symlink_metadata(&backup) {
        Ok(meta) if meta.file_type().is_file() => { std::fs::rename(&backup, path)?; }
        Ok(_) => bail!("respaldo no es un archivo regular: {}", backup.display()),
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => { std::fs::remove_file(path)?; }
        Err(e) => return Err(e.into()),
    }
    Ok(true)
}
pub fn install_command(scope: Scope, yes: bool, dry_run: bool) -> Result<()> {
    let path = home_path(scope)?;
    let exe = std::env::current_exe()?.canonicalize()?;
    let new = contents(&exe)?;
    println!("PI · {}", path.display());
    if current(&path)?.as_deref() == Some(new.as_str()) { println!("Ya está instalado."); return Ok(()); }
    if dry_run { println!("(simulación: no se escribió nada)"); return Ok(()); }
    if !yes && !confirm("¿Instalar la extensión de galgo para PI?")? { println!("Cancelado."); return Ok(()); }
    install(&path, &exe)?;
    println!("Extensión instalada. Reinicia PI o usa /reload.");
    Ok(())
}
pub fn uninstall_command(scope: Scope, yes: bool) -> Result<()> {
    let path = home_path(scope)?;
    if !current(&path)?.is_some_and(|s| s.starts_with(MARKER)) { println!("No hay extensión de galgo en {}", path.display()); return Ok(()); }
    if !yes && !confirm("¿Quitar la extensión de galgo para PI?")? { println!("Cancelado."); return Ok(()); }
    uninstall(&path)?;
    println!("Extensión retirada; se restauró el respaldo si existía.");
    Ok(())
}
pub fn status_command(scope: Scope) -> Result<()> {
    let path = home_path(scope)?;
    let installed = current(&path)?.is_some_and(|s| s.starts_with(MARKER));
    println!("PI · {} {}", path.display(), if installed { "instalado" } else { "no instalado" });
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;
    use serde_json::json;
    #[test]
    fn pi_events() {
        assert_eq!(map_event(&json!({"type":"before_agent_start","messageType":"user"})), Some((HookEvent::PromptSubmitted,None)));
        assert_eq!(map_event(&json!({"type":"before_agent_start","messageType":"custom"})), None);
        assert_eq!(map_event(&json!({"type":"agent_start"})), Some((HookEvent::Working,None)));
        assert_eq!(map_event(&json!({"type":"ui_prompt_start","title":"aprobar"})), Some((HookEvent::Blocked,Some("aprobar".into()))));
        assert_eq!(map_event(&json!({"type":"ui_prompt_end"})), Some((HookEvent::Working,None)));
        assert_eq!(map_event(&json!({"type":"session_start","idle":true})), Some((HookEvent::Idle,None)));
        assert_eq!(map_event(&json!({"type":"agent_settled","outcome":"completed","summary":" listo "})), Some((HookEvent::TurnEnded,Some("listo".into()))));
        assert_eq!(map_event(&json!({"type":"agent_settled","outcome":"failed","error":"falló"})), Some((HookEvent::Failed,Some("falló".into()))));
        assert_eq!(map_event(&json!({"type":"agent_settled","outcome":"unknown"})), Some((HookEvent::Idle,None)));
        assert_eq!(map_event(&json!({"type":"agent_settled"})), None);
        assert_eq!(map_event(&json!({"type":"agent_end"})), None);
        assert_eq!(map_event(&json!({"type":"agent_settled","outcome":"completed","summary":"x".repeat(700)})).unwrap().1.unwrap().chars().count(), 601);
    }
    #[test]
    fn installer_preserves_and_restores_original() {
        let home = std::env::temp_dir().join(format!("galgo-pi-test-{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&home);
        let file = path(&home);
        std::fs::create_dir_all(file.parent().unwrap()).unwrap();
        std::fs::write(&file, "original").unwrap();
        std::fs::write(file.parent().unwrap().join("herdr-agent-state.ts"), "herdr").unwrap();
        assert!(install(&file, Path::new("/tmp/galgo")).unwrap());
        assert!(!install(&file, Path::new("/tmp/galgo")).unwrap());
        assert_eq!(std::fs::read_to_string(backup(&file)).unwrap(), "original");
        assert!(uninstall(&file).unwrap());
        assert_eq!(std::fs::read_to_string(&file).unwrap(), "original");
        assert_eq!(std::fs::read_to_string(file.parent().unwrap().join("herdr-agent-state.ts")).unwrap(), "herdr");
        assert!(!uninstall(&file).unwrap());
        std::fs::remove_dir_all(home).unwrap();
    }
}
